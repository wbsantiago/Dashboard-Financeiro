import fs from 'node:fs';
import path from 'node:path';
import { randomBytes } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tools = path.resolve(repo, '../work/android-tools');
const directory = path.join(tools, 'signing');
const key = path.join(directory, 'financas10-upload.p12'), config = path.join(directory, 'release-signing.properties');
if (fs.existsSync(key) || fs.existsSync(config)) throw new Error('Arquivos de assinatura já existem. Eles não serão substituídos.');
const javaDir = path.join(tools, 'java');
const java = [process.env.JAVA_HOME, ...(fs.existsSync(javaDir) ? fs.readdirSync(javaDir).map(name => path.join(javaDir, name)) : [])].find(p => p && fs.existsSync(path.join(p, 'bin', process.platform === 'win32' ? 'keytool.exe' : 'keytool')));
if (!java) throw new Error('Java não encontrado.');
fs.mkdirSync(directory, { recursive: true });
if (process.platform === 'win32') {
  const identity = spawnSync('whoami.exe', [], { encoding: 'utf8' });
  if (identity.status !== 0) throw new Error('Não foi possível identificar o proprietário da chave.');
  const acl = spawnSync('icacls.exe', [directory, '/inheritance:r', '/grant:r', `${identity.stdout.trim()}:(OI)(CI)F`], { encoding: 'utf8' });
  if (acl.status !== 0) throw new Error('Não foi possível restringir o acesso à pasta de assinatura.');
} else fs.chmodSync(directory, 0o700);
const password = randomBytes(32).toString('hex');
const env = { ...process.env, FINANCAS10_KEY_PASSWORD: password };
const result = spawnSync(path.join(java, 'bin', process.platform === 'win32' ? 'keytool.exe' : 'keytool'), ['-genkeypair', '-keystore', key, '-storetype', 'PKCS12', '-storepass:env', 'FINANCAS10_KEY_PASSWORD', '-keypass:env', 'FINANCAS10_KEY_PASSWORD', '-alias', 'financas10-upload', '-keyalg', 'RSA', '-keysize', '3072', '-validity', '10000', '-dname', 'CN=Financas10 Upload, OU=Android, O=Financas10, C=BR'], { env, encoding: 'utf8' });
if (result.status !== 0) throw new Error('Não foi possível gerar a chave de upload. Confira as ferramentas Java.');
fs.writeFileSync(config, `storeFile=${key.replaceAll('\\', '/') }\nstorePassword=${password}\nkeyAlias=financas10-upload\nkeyPassword=${password}\n`, { mode: 0o600, flag: 'wx' });
const cert = path.join(directory, 'financas10-upload-certificate.pem');
const exported = spawnSync(path.join(java, 'bin', process.platform === 'win32' ? 'keytool.exe' : 'keytool'), ['-exportcert', '-rfc', '-keystore', key, '-storepass:env', 'FINANCAS10_KEY_PASSWORD', '-alias', 'financas10-upload', '-file', cert], { env, encoding: 'utf8' });
if (exported.status !== 0) throw new Error('Chave criada, mas a exportação do certificado falhou. Não gere outra chave.');
console.log(`Chave de upload preparada em ${directory}. Guarde uma cópia protegida dessa pasta. Senhas não são exibidas nem versionadas.`);
